const stagePrecedents: Record<string, StagePrecedents> = Object.fromEntries(
  Object.keys(stageTopicMatchers).map((stageId) => [
    stageId,
    { ppmoOpinions: [], pprcDecisions: [] },
  ]),
);

function findMatchingStageIds(text: string, recordType: keyof StageTopicMatchers): string[] {
  const matchingStageIds = Object.entries(stageTopicMatchers)
    .filter(([, matchers]) => matchers[recordType].test(text))
    .map(([stageId]) => stageId);
  const additionalStageIds = Object.entries(additionalStageTopicMatchers)
    .filter(([, matcher]) => matcher.test(text))
    .map(([stageId]) => stageId);

  return [...new Set([...matchingStageIds, ...additionalStageIds])];
}

procurementGuideData.ops.forEach((record, index) => {
  const subject = record.subject ?? '';
  const matchedStageIds = findMatchingStageIds(subject, 'ppmo');
  const stages = matchedStageIds.length
    ? matchedStageIds
    : findMatchingStageIds(`${subject} ${record.opinion ?? ''}`, 'ppmo');

  stages.forEach((stageId) => {
    stagePrecedents[stageId].ppmoOpinions.push({
      id: `ppmo-${index}`,
      question: subject,
      opinion: record.opinion,
      source: `procurement-guide-data.json · राय क्र. ${record.no}${record.date ? ` · ${record.date}` : ''}`,
    });
  });
});

procurementGuideData.pp.forEach((record, index) => {
  const dispute = record.subject ?? '';
  const matchedStageIds = findMatchingStageIds(dispute, 'pprc');
  const stages = matchedStageIds.length
    ? matchedStageIds
    : findMatchingStageIds(`${dispute} ${record.decision ?? ''}`, 'pprc');

  stages.forEach((stageId) => {
    stagePrecedents[stageId].pprcDecisions.push({
      id: `pprc-${index}`,
      dispute,
      decision: record.decision,
      result: record.type,
      source: `procurement-guide-data.json · विवाद नं. ${record.no}`,
    });
  });
});

export const STAGE_PRECEDENTS = stagePrecedents;
